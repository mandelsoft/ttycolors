// Package ansi provides the building blocks for ANSI output format
// sequences (Select Graphic Rendition, ESC [ ... m) and utility
// functions for strings containing such sequences.
//
// # Model
//
// The parameter list of a sequence is described by a CodeSequence:
//
//   - A Param is a single numeric value, for example 1.
//   - A Code is a sequence of Params separated by SUBPARAM_SEPARATOR (:),
//     for example 1 or 4:3. A Code with more than one Param uses
//     sub parameters.
//   - A CodeSequence is a sequence of Codes separated by
//     PARAM_SEPARATOR (;), for example 1;38;5;3. Param and Code are
//     CodeSequences themselves, others are created with NewCodeSequence
//     and Join.
//   - A Sequence is the encoded byte sequence.
//
// Mode and Modes (and their Append variants) encode CodeSequences
// into escape sequences.
//
// # Parameter separators
//
// Functions requiring arguments, like colors given by an id (38;5;n) or
// RGB values (38;2;r;g;b), can be encoded in two ways: as separate
// parameters separated by PARAM_SEPARATOR (38;5;n), or as a single
// parameter with sub parameters separated by SUBPARAM_SEPARATOR (38:5:n).
//
// This package uses PARAM_SEPARATOR whenever possible:
//
//   - It is supported by practically all terminals, while sub parameters
//     are a later addition, not supported, for example, by the Linux
//     console, GNU screen, older terminal emulators and many simple
//     parsers in tools and libraries.
//   - Depending on the parser, a sequence with sub parameters is ignored
//     completely, reduced to its first value (for example 4:3 to a single
//     underline), or, by naive parsers treating : like ;, misinterpreted
//     as other output modes.
//   - It is the format generated by former versions of this library.
//
// Sub parameters are only used, where the function cannot be expressed
// otherwise or where the semicolon form would be misinterpreted by
// terminals not supporting the function:
//
//   - underline styles (UNDERLINE_DOUBLE, ...), because 4;3 means
//     underline and italic.
//   - underline colors (Code_UL_ID, Code_UL_RGB), because terminals not
//     supporting 58 would interpret the arguments of 58;5;n as other modes.
//
// Package ttycolors uses those codes only with the features
// FeatureUnderlineStyles and FeatureUnderlineColor, which are disabled by
// default. Using them directly with Mode bypasses this protection.
// Modes puts such codes into separate sequences, so that terminals
// dropping a complete sequence because of sub parameters only drop
// those codes.
//
// # Standards
//
// The output format sequences are defined by several standards and
// de-facto standards. The constants of this package are annotated with
// their origin:
//
//   - [ECMA-48]: ECMA-48 "Control Functions for Coded Character Sets"
//     (5th edition 1991, identical to ISO/IEC 6429, successor of ANSI X3.64).
//     It defines the control sequence introducer (CSI), the parameter and
//     sub parameter separators and the function Select Graphic Rendition
//     (SGR, ESC [ ... m) with the basic modes and the 8 standard colors.
//     It reserves the codes 38 and 48 for the color format of ITU-T T.416.
//   - [T.416]: ITU-T Recommendation T.416 (ISO/IEC 8613-6, Open Document
//     Architecture). It defines the extended colors, an indexed color (5)
//     or a direct RGB color (2), given with sub parameters (38:5:n and
//     38:2::r:g:b).
//   - [xterm]: the terminal emulator xterm introduced the semicolon form of
//     the extended colors (38;5;n and 38;2;r;g;b) and the 256 color palette.
//     This form is supported by practically all terminals.
//   - [aixterm]: the terminal emulator of IBM AIX introduced the bright
//     colors (90-97 and 100-107).
//   - [kitty]: the terminal emulator kitty introduced the underline styles
//     (4:0 to 4:5) and the underline colors (58 and 59), which have been
//     adopted by other terminals like VTE based terminals, iTerm2, WezTerm,
//     foot and mintty.
//
// The output format areas (type Covered) are a concept of this package.
//
// # Limitations
//
//   - Only output format sequences (ESC [ ... m) are recognized.
//     The string functions (CharLen, SubString, SplitAt, Strip, ...)
//     treat all other control sequences, like cursor movements (ESC [ 2 A)
//     or erasing lines (ESC [ 2 K), as regular text. For example,
//     CharLen counts ESC [ 2 K as 4 runes.
//   - The scanner maps code 21 (MODE_DOUBLE_UNDERLINE) to S_UNDERLINE (doubly underlined according
//     to ECMA-48). Some terminals, for example the Linux console,
//     interpret it as resetting bold, instead.
//   - The scanner cannot interpret parameters following an extended color
//     (38, 48, 58) with an unknown color kind, they are ignored.
